/* 
Aritméticos:
+ para somar 
- Para subtrair 
* Para multiplicar 
/ Para Dividir
% Calcular resto da divisão (módulo) 
= Atribuição
*/
//Declarar variáveis
let num1= 10;
let num2= 2;

//Processamento e saída
console.log("Soma: ", num1 + num2); //12
console.log("Subtração: ", num1 - num2); //8
console.log("Multiplicação: ", num1 * num2); //20
console.log("Divisão: ", num1 / num2); //5
console.log("Módulo: ", num1 % num2); //0

