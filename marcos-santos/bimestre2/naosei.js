/*
//Lógicos
 && = E, retorna true se ambas das expressões forem verdadeiras
 || = Ou, retorna true se pelo menos uma das expressões é verdadeira
 != = Não, nega uma expressão*/

 let valor1 = true;
 let valor2 = false;
 console.log(valor1 && valor2);
 console.log(valor1 || valor2);
console.log(!valor1);
