let nota = 99;

if (nota >= 90) {
    console.log("Sua menção é MB")
}
 else if (nota < 90 && nota >= 80) {
    console.log("Sua menção é B")
 }

 else if (nota < 80 && nota >= 70) {
    console,log("Sua menção é R")
 }

else if (nota < 70 && nota >= 60) {
    console.log("Sua menção é I")
}

else {
    console.log("Não avaliado")
}

