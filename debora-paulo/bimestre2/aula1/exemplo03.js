/* Operadores e Tipos de Dados
Aritméticos:
 + para Somar
 - para Subtrair
 * para Multiplicar 
 / para Dividir
 % para calcular o resto da divisão (módulo)
 = atribuição
 */
//Declaração de Variáveis:

let num1= 10;
let num2= 2;

console.log("Soma:", num1 + num2); //12
console.log("Subtração:", num1 - num2); // 8
console.log("Multiplicação:", num1 * num2); //20
console.log("Divisão:", num1 / num2); // 5
console.log("Módulo:", num1 % num2); // 0