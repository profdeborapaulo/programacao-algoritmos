/* Operadores Relacionais:
Relacionais:
 > maior que
 < menor que
 >= maior ou igual a 
 <= menor ou igual a
 == igual a
 != diferente de
 === igualdade estrita (compara tanto o valor quanto o tipo de dado)
 !== diferença estrita (compara tanto o valor quanto o tipo de dado)
 */
//Declaração de Variáveis:

let num1= 10;
let num2= 2;
console.log(num1 > num2); // True
console.log(num1 < num2); // False
console.log(num1 >= num2); // True
console.log(num1 <= num2); // False
console.log(num1 == num2); // False
console.log(num1 != num2); // True
console.log(num1 === num2); //False
console.log(num1 !== num2); // True
