/*RELACIONAIS
>maior
<menor
>= maior ou igual
<= menor ou igual
== igual
!=diferente
=== estritamente igual (compara tanto o valor quanto o tipo de dado)
!== estritamente diferente (compara tanto o valor quanto o tipo de dado)
*/

//declaração dos variáveis
let num1= 10;
let num2= 2;
console.log(num1 > num2); //true
console.log(num1 < num2); //false
console.log(num1 >= num2); //true
console.log(num1 <= num2); //false
console.log(num1 == num2); //false
console.log(num1 != num2); //true
console.log(num1 === num2); //false
console.log(num1 !== num2); //true