/*Aritmeticos: +(soma), -(subtração), *(multiplicação), e / (divisão)
*/
//declaração dos variáveis
let num1= 10;
let num2= 2;
console.log("Soma:", num1 + num2) //12
console.log("Subtração:", num1 - num2) //8
console.log("Divisão: ", num1 / num2) //20
console.log("Multiplicação: ", num1 * num2) //5
console.log("Módilo: ", num1 % num2) //0