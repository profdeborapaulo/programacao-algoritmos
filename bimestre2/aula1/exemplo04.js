/*Operadoes Relacionais:
 > maior que
 < menor que
 >= maior ou igual a 
 <= menor ou igual a
 == igual a 
 != diferente de
 === igualdade escrita (compara tanto o valor quanto o tipo de dado)
 !== diferencia escrita (compara tanto o valor quanto o tipo de dado)
 */

// declaração de variaveis

let num1=10;
let num2=2;

console.log(num1 > num2); //true
console.log(num1 < num2); //false
console.log(num1 >= num2); //true
console.log(num1 <= num2); //false
console.log(num1 == num2); //false
console.log(num1 != num2); //true
console.log(num1 === num2); //false
console.log(num1 !== num2); //true