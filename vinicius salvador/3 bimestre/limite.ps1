teste do poligrafo

enunciado: o famoso consultor patrick jane esta auxiliando a policia em uma investigação criminal e precisa de uma ferramenta tecnologica para apoiar a anlise de suspeitos.
para isso, ele solicitou o desenvolvimento de um sistema de teste do poligrafo capaz de coletar informações dos ivestigados e emitir um paracer baseado nas respostas fornecidas.

objetivo do projeto: desenvolver um sistema em javascript para realizar um questionario investigativo e ao final apresentar uma classificação do investigado na ocorrencia.
o sistema devera exibir 10 perguntas ao investigar

requisitos funcionais:

RF01: O sistema devera apresentar as 10 perguntas ao usuario.

RF02: Cada pergunta devera possuir apenas duas opções de resposta: sim/não

RF03: Ao finalizar o teste, o sistema devera contabilizar a quatidade de respostas sim

RF04: O sistema devera emitir um paracer conforme as regras abaixo:
. menos de cinco - inocente.
. 5 - suspeito
. 6 a 8 - cumplice
. 9 a 1- - culpado

RF05: o resultado deve exibir:
.ao finalizar, o sistema devera contabilizar a quantidade de respostas sim
.clasificação do investigado
.mensagem personalizada

regras de utilização de IA

é permitido usae IA para:

.gerar ideias para as perguntas.
.pesquisar sobre a serie.
.esclarecer duvidas pontuais sobre o desenvolvimento do codigo.
.esclarecer duvidas pontuais sobre os erros encontrados.

não é permitido:

.entregar o projeto totalmente gerado por IA sem o entedimento do codigo.
.copiar e colar codigos sem analisar adaptar.
.declarar autoria de um codigo que não é capaz de explicar.

relatorio obrigatorio do uso da IA:

caso utilize qualquer ferramenta de IA voce devera entregar junto do projeto um documento contendo:
a ferramenta utilizada;
o prompt utilizado;
os trechos utilizados, indentificando quais partes do projeto a IA foi utilizada e justificar seu uso.
responder o que voce aprendeu utilizando a ferramenta que antes voce não sabia
