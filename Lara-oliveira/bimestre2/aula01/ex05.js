
/*
&& E, retorna true se ambas expressões são verdade
|| Ou, retorna true se pelo menos uma das expressões forem verdade
!= Não, nega uma expressão lógica (booleana)
*/

let valor1 = true
let valor2 = false

console.log(valor1 && valor2) //false
console.log(valor1 || valor2) //true
console.log(!valor1) //false